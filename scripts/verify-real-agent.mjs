#!/usr/bin/env node
/**
 * Real-agent end-to-end for the artifact centre.
 *
 *   node scripts/verify-real-agent.mjs [--keep] [--task "..."] [--port 3197]
 *
 * Every other artifact check uses a synthetic event or a pre-recorded path. This
 * one runs an actual harness agent on an actual model, has it write an actual
 * file, and then asserts that Pulse recorded it — the only check that can catch
 * a mismatch between the event shape the plugin assumes and the one the agent
 * loop really emits. (That mismatch is not hypothetical: it is how the
 * listeners-inside-the-inject-gate bug was found, where the plugin loaded and
 * then observed nothing at all.)
 *
 * ## Why it needs a profile of its own
 *
 * The task is run through the shipped `headless` profile, which answers one
 * prompt and exits — so the record has to be on disk, not in memory, which is
 * also what proves the shutdown flush works. Mounting Pulse into a shipped
 * profile needs two things the web profile does not:
 *
 *   * `insert:` rather than a bare row, because `--patch` overlays an existing
 *     entry list instead of appending to it;
 *   * an absolute path to `lib/index.js`, because a shipped profile resolves
 *     bare names against the DSH install directory, and ESM refuses a directory
 *     import regardless.
 *
 * ## Cost and safety
 *
 * This spends one real model call, so it is opt-in and never part of `npm test`.
 * It runs in a throwaway DSH home so the user's own roster, tokens and session
 * key are untouched; the home holds a copy of the model credential, so it is
 * removed afterwards unless `--keep` is passed.
 */

import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const args = process.argv.slice(2);

if (args.includes('--help') || args.includes('-h')) {
  console.log(readFileSync(new URL(import.meta.url)).toString().split('*/')[0].replace(/^\/\*\*?/, ''));
  process.exit(0);
}

const keep = args.includes('--keep');
const taskIndex = args.indexOf('--task');
const task =
  taskIndex === -1
    ? '创建文件 pulse-artifact-e2e.md，内容两行：hello 和 artifact。只做这一件事。'
    : String(args[taskIndex + 1] ?? '');
const portIndex = args.indexOf('--port');
const port = portIndex === -1 ? 3197 : Number(args[portIndex + 1]);

/** The file the task is expected to produce. */
const ARTIFACT_NAME = 'pulse-artifact-e2e.md';

const results = [];
/**
 * Record a check.
 * @param {string} name - what was checked.
 * @param {boolean} ok - whether it passed.
 * @param {string} detail - evidence.
 * @returns {void}
 */
function record(name, ok, detail) {
  results.push({ name, ok: Boolean(ok), detail: String(detail ?? '') });
}

/**
 * Locate the DSH CLI entry module.
 * @returns {string | null} the path, or null.
 */
function findDshBin() {
  const candidates = [
    process.env.DSH_BIN,
    join(process.env.APPDATA ?? join(homedir(), 'AppData', 'Roaming'), 'npm', 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js'),
    '/usr/local/lib/node_modules/@deepseek-ai/dsh/lib/bin.js',
    '/usr/lib/node_modules/@deepseek-ai/dsh/lib/bin.js',
  ].filter(Boolean);
  for (const candidate of candidates) if (existsSync(candidate)) return candidate;
  return null;
}

const dshBin = findDshBin();
if (!dshBin) {
  console.error('找不到 DSH CLI。设置 DSH_BIN 指向 .../@deepseek-ai/dsh/lib/bin.js');
  process.exit(2);
}

// ---- an isolated home, seeded with the model credential --------------------

const sourceHome = process.env.DSH_HOME || join(homedir(), '.dsh');
const scratch = join(repo, '.dsh-real-agent-e2e');
const work = join(scratch, 'work');
rmSync(scratch, { recursive: true, force: true });
mkdirSync(work, { recursive: true });

let seeded = 0;
for (const name of ['.credentials.yaml', 'settings.yaml', '.anonymous-user-id']) {
  const from = join(sourceHome, name);
  if (!existsSync(from)) continue;
  copyFileSync(from, join(scratch, name));
  seeded += 1;
}
record('拿到了模型凭据', seeded > 0, `copied ${seeded} file(s) from ${sourceHome}`);
if (seeded === 0) {
  console.error(`\n${sourceHome} 里没有 .credentials.yaml，无法跑真实任务。`);
  rmSync(scratch, { recursive: true, force: true });
  process.exit(2);
}

// ---- the overlay that mounts Pulse into the shipped headless profile -------

const patchPath = join(scratch, 'pulse-headless.yml');
writeFileSync(
  patchPath,
  [
    '# Generated by scripts/verify-real-agent.mjs',
    '- insert:',
    '    - id: remote-pulse',
    `      name: '${join(repo, 'lib', 'index.js').replace(/\\/g, '/')}'`,
    '      config:',
    "        host: '127.0.0.1'",
    `        port: ${port}`,
    "        realm: 'Pulse'",
    "        notify: 'none'",
    '',
  ].join('\n'),
  'utf8',
);

// ---- run one real task ------------------------------------------------------

console.log(`Pulse 真实 agent 端到端  bin=${dshBin}`);
console.log(`  home   : ${scratch}`);
console.log(`  task   : ${task}`);
console.log('  这一步会真的调用一次模型，请稍候…');
console.log('');

const run = spawnSync(process.execPath, [dshBin, '--profile', 'headless', '--patch', patchPath, task], {
  cwd: work,
  env: { ...process.env, DSH_HOME: scratch },
  encoding: 'utf8',
  stdio: 'inherit',
});
record('真实任务执行完成', run.status === 0, `exit=${run.status}`);

// ---- did the file get written, and did Pulse record it? --------------------

const produced = join(work, ARTIFACT_NAME);
const producedOk = existsSync(produced);
record('agent 真的写了文件', producedOk, producedOk ? produced : `${produced} 不存在`);

const recordFile = join(scratch, 'remote-pulse', 'artifacts.json');
let recorded = null;
if (existsSync(recordFile)) {
  try {
    recorded = JSON.parse(readFileSync(recordFile, 'utf8'));
  } catch {
    recorded = null;
  }
}
record(
  'Pulse 记录到了这个产物',
  Array.isArray(recorded) && recorded.some(entry => entry.name === ARTIFACT_NAME),
  Array.isArray(recorded) ? `${recorded.length} 条：${recorded.map(entry => entry.name).join(', ')}` : '没有 artifacts.json',
);

if (Array.isArray(recorded)) {
  const entry = recorded.find(candidate => candidate.name === ARTIFACT_NAME);
  if (entry) {
    record('记录里带路径、工具和会话', Boolean(entry.path && entry.tool && entry.sessionId), JSON.stringify(entry));
    record('按扩展名判定为文本', entry.kind === 'text', `kind=${entry.kind}`);
    // The content route serves only paths in this index, so the recorded path
    // must be the real file the agent wrote.
    record('记录指向真实文件', existsSync(entry.path), entry.path);
  }
}

// ---- report and clean up ---------------------------------------------------

console.log('');
let failed = 0;
for (const result of results) {
  if (!result.ok) failed += 1;
  console.log(`  ${result.ok ? 'ok  ' : 'FAIL'} ${result.name}${result.detail ? `   (${result.detail})` : ''}`);
}
console.log('');
console.log(failed === 0 ? '全部通过' : `${failed} 项失败`);

if (keep) {
  console.log(`\n保留现场：${scratch}（里面有模型凭据副本，记得自己删）`);
} else {
  rmSync(scratch, { recursive: true, force: true });
  console.log(`\n已清理 ${scratch}`);
}

process.exitCode = failed === 0 ? 0 : 1;
